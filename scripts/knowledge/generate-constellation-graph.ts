/**
 * Constellation Graph Generator (Phase 1.6 prep)
 *
 * Emits the hierarchical knowledge-graph node set for `@opencosmos/constellation`:
 *   tradition  → synthesized from `tradition` (fallback `domain`) per source work
 *   work       → every doc in knowledge/sources/ with work_type: 'work'
 *   section    → every H2 heading inside a work
 *   quote      → every embeddable quote in knowledge/quotes/*.yaml
 *
 * Edges:
 *   tradition → work     type: 'hierarchy'
 *   work      → section  type: 'contains'
 *   quote     → work     type: 'cites'        (when source_work resolves to a known work)
 *   quote     → tradition type: 'member_of'   (fallback when source_work is null)
 *
 * After topology is built, ForceAtlas2 settles positions. The result is written
 * to Upstash Redis under two keys:
 *   knowledge:constellation         — full graph, gzip-compressed, Base64-encoded
 *   knowledge:constellation:preview — top 40 nodes by degree, < 5KB
 *
 * The legacy wiki graph (knowledge:graph) is generated by generate-wiki-graph.ts
 * and is unchanged — the sigma renderer at /knowledge/graph keeps working until
 * the constellation package replaces it in Phase 1.6 proper.
 *
 * Usage: pnpm graph:constellation
 */

